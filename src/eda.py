"""Exploratory data analysis for retail sales."""

import matplotlib

# Use a non-interactive backend to save charts without opening windows.
matplotlib.use("Agg")

import matplotlib.pyplot as plt
import pandas as pd

from src.config import FIGURES_DIR, PROCESSED_DATA_DIR


def load_sales() -> pd.DataFrame:
    """Load the cleaned sales dataset."""
    sales_path = PROCESSED_DATA_DIR / "cleaned_sales.csv"

    if not sales_path.exists():
        raise FileNotFoundError(
            "Cleaned sales data not found. "
            "Run python -m src.preprocessing first."
        )

    sales = pd.read_csv(sales_path, parse_dates=["date"])
    return sales


def create_sales_trend(sales: pd.DataFrame) -> None:
    """Plot total daily units sold."""
    daily_sales = (
        sales.groupby("date", as_index=False)["units_sold"]
        .sum()
        .sort_values("date")
    )

    fig, ax = plt.subplots(figsize=(11, 5))

    ax.plot(
        daily_sales["date"],
        daily_sales["units_sold"],
        linewidth=1.8,
        label="Daily units sold",
    )

    ax.set_title("Daily Retail Sales Trend")
    ax.set_xlabel("Date")
    ax.set_ylabel("Units Sold")
    ax.grid(True, alpha=0.3)
    ax.legend()

    fig.autofmt_xdate()
    fig.tight_layout()

    output_path = FIGURES_DIR / "daily_sales_trend.png"
    fig.savefig(output_path, dpi=150)
    plt.close(fig)

    print(f"Saved: {output_path}")


def create_top_products_chart(sales: pd.DataFrame) -> None:
    """Plot the products with the highest total sales."""
    product_sales = (
        sales.groupby("product_name")["units_sold"]
        .sum()
        .sort_values(ascending=True)
    )

    fig, ax = plt.subplots(figsize=(10, 6))

    product_sales.plot(
        kind="barh",
        ax=ax,
    )

    ax.set_title("Total Units Sold by Product")
    ax.set_xlabel("Total Units Sold")
    ax.set_ylabel("Product")
    ax.grid(axis="x", alpha=0.3)

    fig.tight_layout()

    output_path = FIGURES_DIR / "top_products.png"
    fig.savefig(output_path, dpi=150)
    plt.close(fig)

    print(f"Saved: {output_path}")


def create_category_revenue_chart(sales: pd.DataFrame) -> None:
    """Plot total revenue generated by each category."""
    category_revenue = (
        sales.groupby("category")["revenue"]
        .sum()
        .sort_values(ascending=False)
    )

    fig, ax = plt.subplots(figsize=(9, 5))

    category_revenue.plot(
        kind="bar",
        ax=ax,
    )

    ax.set_title("Revenue by Product Category")
    ax.set_xlabel("Category")
    ax.set_ylabel("Simulated Revenue")
    ax.tick_params(axis="x", rotation=30)
    ax.grid(axis="y", alpha=0.3)

    fig.tight_layout()

    output_path = FIGURES_DIR / "category_revenue.png"
    fig.savefig(output_path, dpi=150)
    plt.close(fig)

    print(f"Saved: {output_path}")


def create_weekday_chart(sales: pd.DataFrame) -> None:
    """Compare average daily sales across weekdays."""
    daily_store_sales = (
        sales.groupby(["date", "store_id"], as_index=False)["units_sold"]
        .sum()
    )

    daily_store_sales["weekday"] = (
        daily_store_sales["date"].dt.day_name()
    )

    weekday_order = [
        "Monday",
        "Tuesday",
        "Wednesday",
        "Thursday",
        "Friday",
        "Saturday",
        "Sunday",
    ]

    weekday_sales = (
        daily_store_sales.groupby("weekday")["units_sold"]
        .mean()
        .reindex(weekday_order)
    )

    fig, ax = plt.subplots(figsize=(10, 5))

    weekday_sales.plot(
        kind="bar",
        ax=ax,
    )

    ax.set_title("Average Daily Sales by Weekday and Store")
    ax.set_xlabel("Weekday")
    ax.set_ylabel("Average Units Sold per Store")
    ax.tick_params(axis="x", rotation=30)
    ax.grid(axis="y", alpha=0.3)

    fig.tight_layout()

    output_path = FIGURES_DIR / "weekday_sales.png"
    fig.savefig(output_path, dpi=150)
    plt.close(fig)

    print(f"Saved: {output_path}")


def print_sales_summary(sales: pd.DataFrame) -> None:
    """Print key descriptive statistics."""
    total_units = int(sales["units_sold"].sum())
    total_revenue = float(sales["revenue"].sum())
    zero_sales_percentage = (
        sales["units_sold"].eq(0).mean() * 100
    )

    print("\n" + "=" * 55)
    print("EXPLORATORY DATA ANALYSIS SUMMARY")
    print("=" * 55)

    print(f"Sales records: {len(sales):,}")
    print(f"Stores: {sales['store_id'].nunique()}")
    print(f"Products: {sales['product_id'].nunique()}")
    print(f"Total units sold: {total_units:,}")
    print(f"Total simulated revenue: {total_revenue:,.2f}")
    print(f"Zero-sales records: {zero_sales_percentage:.2f}%")

    print("\nTop 5 products by units sold:")

    top_products = (
        sales.groupby("product_name")["units_sold"]
        .sum()
        .sort_values(ascending=False)
        .head(5)
    )

    print(top_products.to_string())

    print("\nRevenue by category:")

    category_revenue = (
        sales.groupby("category")["revenue"]
        .sum()
        .sort_values(ascending=False)
    )

    print(category_revenue.to_string())


def run_eda() -> None:
    """Run the complete EDA workflow."""
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)

    sales = load_sales()

    print_sales_summary(sales)

    create_sales_trend(sales)
    create_top_products_chart(sales)
    create_category_revenue_chart(sales)
    create_weekday_chart(sales)

    print("\nEDA completed successfully.")


if __name__ == "__main__":
    run_eda()